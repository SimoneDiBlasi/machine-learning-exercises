"""
CL02 - Anomaly Detection with DBSCAN

Objective:
Use DBSCAN to identify clusters and potential anomalies in a synthetic dataset.

Requirements:
1. Generate and explore a synthetic dataset.
2. Visualize the original data distribution.
3. Standardize the features.
4. Apply DBSCAN clustering.
5. Identify clusters and noise points.
6. Visualize the clustering results.
7. Compare different DBSCAN parameter configurations.
8. Analyze the effect of eps and min_samples.
"""

from sklearn.datasets import make_moons
from sklearn.preprocessing import StandardScaler
from sklearn.cluster import DBSCAN

import pandas as pd
import matplotlib.pyplot as plt


# ------------------------------------------------------------
# HELPER FUNCTION
# ------------------------------------------------------------

def print_section(title: str) -> None:
    """Print a formatted section title."""
    print("\n" + "=" * 60)
    print(title)
    print("=" * 60)


# ------------------------------------------------------------
# 1. GENERATE THE DATASET
# ------------------------------------------------------------

print_section("1. DATASET GENERATION")

X, y_true = make_moons(
    n_samples=500,
    noise=0.08,
    random_state=42
)

df = pd.DataFrame(
    X,
    columns=["Feature_1", "Feature_2"]
)

print(f"\nNumber of samples: {df.shape[0]}")
print(f"Number of features: {df.shape[1]}")


# ------------------------------------------------------------
# 2. EXPLORE THE DATASET
# ------------------------------------------------------------

print_section("2. DATASET EXPLORATION")

print("\nFirst five rows:")
print(df.head())

print("\nDataset information:")
df.info()

print("\nDataset shape:")
print(df.shape)

print("\nStatistical summary:")
print(df.describe())

print("\nMissing values:")
print(df.isnull().sum())


# ------------------------------------------------------------
# 3. VISUALIZE THE ORIGINAL DATASET
# ------------------------------------------------------------

print_section("3. ORIGINAL DATA VISUALIZATION")

plt.figure(figsize=(8, 6))

plt.scatter(
    df["Feature_1"],
    df["Feature_2"],
    s=40,
    alpha=0.7
)

plt.title("Synthetic Dataset Before Clustering")
plt.xlabel("Feature 1")
plt.ylabel("Feature 2")
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()


# ------------------------------------------------------------
# 4. VISUALIZE THE ORIGINAL GROUPS
# ------------------------------------------------------------

print_section("4. ORIGINAL GROUPS (REFERENCE ONLY)")

plt.figure(figsize=(8, 6))

plt.scatter(
    X[:, 0],
    X[:, 1],
    c=y_true,
    cmap="viridis",
    s=40,
    alpha=0.7
)

plt.title("Original Groups Generated by make_moons")
plt.xlabel("Feature 1")
plt.ylabel("Feature 2")
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()


# ------------------------------------------------------------
# 5. FEATURE SCALING
# ------------------------------------------------------------

print_section("5. FEATURE SCALING")

scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

print("\nFirst five rows after scaling:")
print(X_scaled[:5].round(4))

print("\nFeature means:")
print(X_scaled.mean(axis=0).round(4))

print("\nFeature standard deviations:")
print(X_scaled.std(axis=0).round(4))


# ------------------------------------------------------------
# 6. DBSCAN CLUSTERING
# ------------------------------------------------------------

print_section("6. DBSCAN CLUSTERING")

eps_value = 0.15
min_samples_value = 5

dbscan = DBSCAN(
    eps=eps_value,
    min_samples=min_samples_value
)

cluster_labels = dbscan.fit_predict(X_scaled)
df["Cluster"] = cluster_labels

n_clusters = len(set(cluster_labels)) - (
    1 if -1 in cluster_labels else 0
)

n_noise = int((cluster_labels == -1).sum())
noise_percentage = n_noise / len(cluster_labels) * 100

print(f"\neps: {eps_value}")
print(f"min_samples: {min_samples_value}")
print(f"Number of clusters: {n_clusters}")
print(f"Number of noise points: {n_noise}")
print(f"Noise percentage: {noise_percentage:.2f}%")

print("\nNumber of points per cluster:")
print(df["Cluster"].value_counts().sort_index())


# ------------------------------------------------------------
# 7. VISUALIZE CLUSTERS AND NOISE
# ------------------------------------------------------------

print_section("7. CLUSTER AND NOISE VISUALIZATION")

noise_mask = cluster_labels == -1
clustered_mask = ~noise_mask

plt.figure(figsize=(9, 6))

if clustered_mask.any():
    plt.scatter(
        X_scaled[clustered_mask, 0],
        X_scaled[clustered_mask, 1],
        c=cluster_labels[clustered_mask],
        cmap="viridis",
        s=40,
        alpha=0.7,
        label="Clustered points"
    )

if noise_mask.any():
    plt.scatter(
        X_scaled[noise_mask, 0],
        X_scaled[noise_mask, 1],
        c="red",
        marker="x",
        s=80,
        label="Noise / potential anomalies"
    )

plt.title(
    f"DBSCAN Clustering (eps={eps_value}, "
    f"min_samples={min_samples_value})"
)
plt.xlabel("Feature 1 (Standardized)")
plt.ylabel("Feature 2 (Standardized)")
plt.legend()
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()


# ------------------------------------------------------------
# 8. DISPLAY NOISE POINTS
# ------------------------------------------------------------

print_section("8. NOISE POINT ANALYSIS")

noise_points = df.loc[
    df["Cluster"] == -1,
    ["Feature_1", "Feature_2", "Cluster"]
]

if noise_points.empty:
    print("\nNo noise points were detected.")
else:
    print(f"\nTotal noise points: {len(noise_points)}")
    print("\nFirst noise points:")
    print(noise_points.head(10).to_string(index=False))


# ------------------------------------------------------------
# 9. DBSCAN PARAMETER COMPARISON
# ------------------------------------------------------------

print_section("9. DBSCAN PARAMETER COMPARISON")

parameter_results = []

eps_values = [0.1, 0.15, 0.2, 0.3, 0.4]
min_samples_values = [5, 10]

for min_samples in min_samples_values:
    for eps in eps_values:
        model = DBSCAN(
            eps=eps,
            min_samples=min_samples
        )

        labels = model.fit_predict(X_scaled)

        number_of_clusters = len(set(labels)) - (
            1 if -1 in labels else 0
        )

        number_of_noise = int((labels == -1).sum())
        noise_percentage = number_of_noise / len(labels) * 100

        parameter_results.append({
            "eps": eps,
            "min_samples": min_samples,
            "clusters": number_of_clusters,
            "noise_points": number_of_noise,
            "noise_percentage": round(noise_percentage, 2)
        })

results_df = pd.DataFrame(parameter_results)

print("\nComparison results:")
print(results_df.to_string(index=False))


# ------------------------------------------------------------
# 10. VISUALIZE THE PARAMETER COMPARISON
# ------------------------------------------------------------

print_section("10. PARAMETER COMPARISON VISUALIZATION")

fig, axes = plt.subplots(1, 2, figsize=(12, 5))

for min_samples in min_samples_values:
    subset = results_df[
        results_df["min_samples"] == min_samples
    ]

    axes[0].plot(
        subset["eps"],
        subset["clusters"],
        marker="o",
        label=f"min_samples={min_samples}"
    )

    axes[1].plot(
        subset["eps"],
        subset["noise_points"],
        marker="o",
        label=f"min_samples={min_samples}"
    )

axes[0].set_title("Number of Clusters")
axes[0].set_xlabel("eps")
axes[0].set_ylabel("Number of Clusters")
axes[0].legend()
axes[0].grid(True, alpha=0.3)

axes[1].set_title("Number of Noise Points")
axes[1].set_xlabel("eps")
axes[1].set_ylabel("Number of Noise Points")
axes[1].legend()
axes[1].grid(True, alpha=0.3)

plt.tight_layout()
plt.show()


# ------------------------------------------------------------
# 11. FINAL SUMMARY
# ------------------------------------------------------------

print_section("11. FINAL SUMMARY")

print(f"\nDataset size: {len(df)}")
print(f"Selected eps: {eps_value}")
print(f"Selected min_samples: {min_samples_value}")
print(f"Detected clusters: {n_clusters}")
print(f"Detected noise points: {n_noise}")
print(f"Noise percentage: {noise_percentage:.2f}%")
