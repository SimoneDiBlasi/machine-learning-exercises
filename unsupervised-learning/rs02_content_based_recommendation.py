
"""
Exercise RS02 - Content-Based Movie Recommendation System

Objective:
    Build a movie recommendation system that suggests movies
    based on their content and characteristics.

Dataset:
    MovieLens latest-small

Features:
    - Movie titles
    - Movie genres

Concepts:
    - Content-Based Filtering
    - Feature Extraction
    - Multi-Hot Encoding
    - Feature Vectors
    - Cosine Similarity
    - Movie Similarity
    - Recommendation Ranking

Tasks:
    1. Load and explore the movie dataset.
    2. Extract and analyze the available movie genres.
    3. Convert movie genres into numerical feature vectors.
    4. Calculate movie similarities using cosine similarity.
    5. Implement a function that recommends similar movies
       based on a selected movie title.
    6. Display the top recommendations for a given movie.

Expected Outcome:
    Given a movie title, the system returns a ranked list
    of similar movies based on their genres.

Notes:
    This recommendation system does not require user ratings
    or user similarity. Recommendations are generated by
    comparing movie characteristics.
"""

from pathlib import Path

import pandas as pd
from sklearn.preprocessing import MultiLabelBinarizer
from sklearn.metrics.pairwise import cosine_similarity


# ============================================================
# 1. Load the dataset
# ============================================================

DATASET_PATH = (
    Path(__file__).parent
    / "datasets"
    / "ml-latest-small"
)

movies = pd.read_csv(DATASET_PATH / "movies.csv")


# ============================================================
# 2. Explore the dataset
# ============================================================

print("=== Dataset Overview ===")

print(f"Number of movies: {len(movies)}")
print(f"Number of columns: {len(movies.columns)}")

print("\nDataset columns:")
print(movies.columns.tolist())

print("\nFirst 10 movies:")
print(movies.head(10).to_string(index=False))


# ============================================================
# 3. Explore movie genres
# ============================================================

print("\n=== Available Genres ===")

all_genres = (
    movies["genres"]
    .str.split("|")
    .explode()
    .dropna()
    .unique()
)

all_genres = sorted(
    genre
    for genre in all_genres
    if genre != "(no genres listed)"
)

print(f"Number of genres: {len(all_genres)}")
print(all_genres)


# ============================================================
# 4. Inspect a sample movie
# ============================================================

movie_title = "Toy Story (1995)"

selected_movie = movies[
    movies["title"] == movie_title
]

if selected_movie.empty:
    print(f"\nMovie not found: {movie_title}")
else:
    print(f"\n=== Selected Movie: {movie_title} ===")
    print(selected_movie.to_string(index=False))


# ============================================================
# 5. Convert movie genres into numerical feature vectors
# ============================================================

# Convert each movie's genre string into a list of genres.
movies["genre_list"] = movies["genres"].apply(
    lambda genres: (
        []
        if genres == "(no genres listed)"
        else genres.split("|")
    )
)

# Create a binary feature for each genre.
mlb = MultiLabelBinarizer()

genre_matrix = mlb.fit_transform(movies["genre_list"])

# Store the feature vectors in a DataFrame.
genre_features = pd.DataFrame(
    genre_matrix,
    columns=mlb.classes_,
    index=movies["movieId"],
)

print("\n=== Genre Feature Matrix ===")
print(f"Matrix shape: {genre_features.shape}")

print("\nFirst 10 movie feature vectors:")
print(genre_features.head(10))

# Inspect the feature vector for Toy Story.
toy_story = movies[
    movies["title"] == "Toy Story (1995)"
]

if not toy_story.empty:
    toy_story_id = int(toy_story.iloc[0]["movieId"])

    print("\n=== Toy Story Feature Vector ===")
    print(genre_features.loc[toy_story_id])


# ============================================================
# 6. Calculate cosine similarity between movies
# ============================================================

# Calculate the similarity between every pair of movies.
similarity_matrix = cosine_similarity(genre_features)

# Use movie IDs as row and column labels.
similarity_df = pd.DataFrame(
    similarity_matrix,
    index=genre_features.index,
    columns=genre_features.index,
)

print("\n=== Movie Similarity Matrix ===")
print(f"Matrix shape: {similarity_df.shape}")

# Inspect the similarity of Toy Story against other movies.
toy_story = movies[
    movies["title"] == "Toy Story (1995)"
]

if not toy_story.empty:
    toy_story_id = int(toy_story.iloc[0]["movieId"])

    toy_story_similarities = similarity_df[toy_story_id]

    print("\n=== Toy Story Similarity Scores ===")
    print(
        toy_story_similarities
        .sort_values(ascending=False)
        .head(10)
    )


# ============================================================
# 7. Recommend similar movies
# ============================================================

def recommend_similar_movies(
    movie_title: str,
    n_recommendations: int = 10,
) -> pd.DataFrame:
    """
    Recommend movies similar to a selected movie.

    Args:
        movie_title: Title of the movie used as a reference.
        n_recommendations: Maximum number of movies to recommend.

    Returns:
        A DataFrame containing similar movies and their similarity scores.
    """

    if n_recommendations < 1:
        raise ValueError("n_recommendations must be at least 1.")

    # Find the selected movie, ignoring title capitalization.
    selected_movie = movies[
        movies["title"].str.casefold() == movie_title.casefold()
    ]

    if selected_movie.empty:
        raise ValueError(f"Movie not found: {movie_title}")

    movie_id = int(selected_movie.iloc[0]["movieId"])

    # Get similarity scores for the selected movie.
    similarity_scores = similarity_df[movie_id]

    # Exclude the selected movie from the recommendations.
    similarity_scores = similarity_scores.drop(index=movie_id)

    # Select the most similar movies.
    top_movies = similarity_scores.nlargest(n_recommendations)

    # Retrieve movie information in similarity ranking order.
    recommendations = (
        movies[movies["movieId"].isin(top_movies.index)]
        [["movieId", "title", "genres"]]
        .set_index("movieId")
        .loc[top_movies.index]
        .reset_index()
    )

    # Add similarity scores.
    recommendations["similarity"] = top_movies.to_numpy()

    return recommendations


# ============================================================
# 8. Generate recommendations
# ============================================================

movie_title = "Toy Story (1995)"

try:
    recommendations = recommend_similar_movies(
        movie_title=movie_title,
        n_recommendations=10,
    )

    print(f"\n=== Movies Similar to {movie_title} ===")
    print(recommendations.to_string(index=False))

except ValueError as error:
    print(f"\nRecommendation error: {error}")


# ============================================================
# 9. Project summary
# ============================================================

print("\n=== Project Summary ===")
print("Dataset: MovieLens latest-small")
print("Approach: Content-Based Filtering")
print("Features: Movie genres")
print("Encoding: Multi-Hot Encoding")
print("Similarity metric: Cosine Similarity")
